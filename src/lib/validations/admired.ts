import { z } from "zod"
import { PHONE_PHOTO_MAX_BASE64 } from "./photo-upload"

/**
 * ADMIRED — watches seen and admired, not to be owned (migration 00056).
 * The contract between the API routes and the iPhone app, which imports this
 * file; the web's Server Actions validate with it too.
 */

/** Why it caught the eye. Order is display order. */
export const ADMIRED_TAGS = ["design", "finishing", "complication", "photography"] as const
export type AdmiredTag = (typeof ADMIRED_TAGS)[number]
export const admiredTagLabels: Record<AdmiredTag, string> = {
  design: "Design",
  finishing: "Finishing",
  complication: "Complication",
  photography: "Photography",
}

export const ADMIRED_PHOTO_KINDS = ["watch", "placard"] as const
export type AdmiredPhotoKind = (typeof ADMIRED_PHOTO_KINDS)[number]

const isoDate = z.string().regex(/^\d{4}-\d{2}-\d{2}$/, "Date must be YYYY-MM-DD")
const optText = (max: number) => z.string().trim().max(max).nullable().optional()

/** The editable fields (web edit dialog, phone corrections). */
export const admiredFieldsSchema = z.object({
  event: optText(120),
  maker: optText(120),
  model: optText(200),
  reference: optText(80),
  price_text: optText(80),
  notes: optText(2000),
  tags: z.array(z.enum(ADMIRED_TAGS)).max(ADMIRED_TAGS.length).optional(),
  seen_on: isoDate.optional(),
})
export type AdmiredFields = z.input<typeof admiredFieldsSchema>

/**
 * POST /api/admired. `id` is generated BY THE PHONE so a capture queued
 * offline can be retried safely — a repeat insert is treated as done.
 */
export const admiredCreateSchema = admiredFieldsSchema.extend({
  id: z.string().uuid(),
  seen_on: isoDate,
})
export type AdmiredCreate = z.input<typeof admiredCreateSchema>

/** POST /api/admired/:id/photos — one frame; `id` client-generated, as above. */
export const admiredPhotoUploadSchema = z.object({
  id: z.string().uuid(),
  kind: z.enum(ADMIRED_PHOTO_KINDS),
  image_base64: z.string().min(1, "A photo is required").max(PHONE_PHOTO_MAX_BASE64),
  media_type: z.enum(["image/jpeg", "image/png", "image/webp", "image/heic"]),
  /** Order within the admired watch (the phone's shot order). */
  display_order: z.number().int().min(0).max(10_000).optional(),
})
export type AdmiredPhotoUpload = z.input<typeof admiredPhotoUploadSchema>

/**
 * What the placard reader must return — structured output. Null for anything
 * not printed on the card; never guessed from the watch itself.
 */
export const placardReadSchema = z.object({
  /** False when the image isn't a readable placard / card / sign. */
  legible: z.boolean(),
  maker: z.string().nullable(),
  model: z.string().nullable(),
  reference: z.string().nullable(),
  /** Exactly as printed, currency included ("CHF 48,000"), or "Price on request". */
  price_text: z.string().nullable(),
  /** Other printed facts worth keeping: movement, limited edition, materials. One or two short lines. */
  details: z.string().nullable(),
})
export type PlacardRead = z.infer<typeof placardReadSchema>

/** What the photo route returns. */
export interface AdmiredPhotoResponse {
  photoId: string
  /** Set when this frame was a placard and was read. */
  placard?: {
    read: PlacardRead
    /** The fields the read actually filled (empty ones only). */
    filled: Array<"maker" | "model" | "reference" | "price_text" | "notes">
    cost_usd: number
  }
  /** A placard that couldn't be read — the frame is still saved. */
  placardError?: string
}
